"""
Static site builder for synthetic content demo.
Wraps generated articles in HTML with mandatory disclaimers and no-index tags.
Outputs to /docs (GitHub Pages compatible) or /dist (Netlify compatible).
"""

from __future__ import annotations
import json
import os
import shutil
from pathlib import Path
from datetime import datetime, timezone
from typing import Optional


