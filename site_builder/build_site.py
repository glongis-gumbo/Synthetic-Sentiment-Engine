ROBOTS_TXT = """\
# Disallow all crawlers — this site contains synthetic test content only
User-agent: *
Disallow: /
"""


def build_static_site(
    results_json_path: str,
    output_dir: str = "docs",       # "docs" = GitHub Pages, "dist" = Netlify
) -> None:
    out = Path(output_dir)
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    with open(results_json_path) as f:
        results = json.load(f)

    # Flatten — results_json may be summary or raw content list
    articles = results if isinstance(results, list) else results.get("contents", [])

    index_rows = []
    generated_count = 0

    for i, item in enumerate(articles):
        ticker = item.get("ticker", "UNK")
        polarity = item.get("polarity", "neutral")
        intensity = item.get("intensity", 0.0)
        score = item.get("sentiment_score") or 0.0
        fmt = item.get("format", "unknown")
        scenario = item.get("metadata", {}).get("scenario_id", item.get("scenario_id", "unknown"))
        text = item.get("text", "[no content]")
        timestamp = item.get("timestamp", "")

        filename = f"article_{i:04d}_{ticker}_{polarity}.html"
        filepath = out / filename

        page_html = HTML_TEMPLATE.format(
            disclaimer=DISCLAIMER_BANNER,
            ticker=ticker,
            scenario_id=scenario,
            polarity=polarity,
            intensity=f"{intensity:.2f}",
            sentiment_score=f"{score:+.2f}",
            content_format=fmt,
            timestamp=timestamp[:19] if timestamp else "N/A",
            article_text=text,
        )
        filepath.write_text(page_html, encoding="utf-8")
        generated_count += 1

        index_rows.append(
            f'<tr>'
            f'<td>${ticker}</td>'
            f'<td class="{polarity}">{polarity}</td>'
            f'<td>{intensity:.2f}</td>'
            f'<td>{score:+.2f}</td>'
            f'<td>{fmt}</td>'
            f'<td>{scenario}</td>'
            f'<td><a href="{filename}">view</a></td>'
            f'</tr>'
        )

    # Write index
    index_html = INDEX_TEMPLATE.format(
        disclaimer=DISCLAIMER_BANNER,
        generated_at=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        total=generated_count,
        rows="\n      ".join(index_rows),
    )
    (out / "index.html").write_text(index_html, encoding="utf-8")

    # Write robots.txt — block all crawlers
    (out / "robots.txt").write_text(ROBOTS_TXT, encoding="utf-8")

    # Write _headers for Netlify (also sets X-Robots-Tag at HTTP level)
    netlify_headers = """\
/*
  X-Robots-Tag: noindex, nofollow
  Cache-Control: no-store
"""
    (out / "_headers").write_text(netlify_headers, encoding="utf-8")

    print(f"Site built: {generated_count} pages → {out}/")
    print(f"  index.html       — article index")
    print(f"  robots.txt       — blocks all crawlers")
    print(f"  _headers         — Netlify HTTP-level noindex")
    print(f"\nDeploy options:")
    print(f"  GitHub Pages: push repo, set Pages source to /{output_dir}")
    print(f"  Netlify:      drag-and-drop the '{output_dir}' folder at app.netlify.com/drop")


if __name__ == "__main__":
    import sys
    results_path = sys.argv[1] if len(sys.argv) > 1 else "stress_test_results.json"
    output = sys.argv[2] if len(sys.argv) > 2 else "docs"
    build_static_site(results_path, output)
